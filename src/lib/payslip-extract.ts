const MONTHS = [
  'january', 'february', 'march', 'april', 'may', 'june',
  'july', 'august', 'september', 'october', 'november', 'december',
]

/* ------------------------------------------------------- Label vocabulary */

/**
 * Words that mark a line as a DEDUCTION. Checked before the earnings list,
 * because "Professional Tax" and "Income Tax" would otherwise be caught by a
 * generic allowance match.
 */
const DEDUCTION_WORDS = [
  'deduction', 'tax', 'tds', 'pf', 'provident', 'esi', 'esic', ' pt ', 'professional tax',
  'insurance', 'medicare', 'social security', 'withhold', 'loan', 'advance', 'recovery',
  'lop', 'leave without pay', 'contribution', 'nps', 'gratuity recovery', 'federal',
  'state income', 'local income', 'fica', 'garnish', 'premium', '401k', 'roth',
]

/** Words that mark a line as an EARNING. */
const EARNING_WORDS = [
  'basic', 'hra', 'house rent', 'allowance', 'conveyance', 'special', 'medical',
  'bonus', 'incentive', 'commission', 'overtime', 'ot ', 'arrear', 'reimbursement',
  'earning', 'salary', 'wage', 'stipend', 'regular', 'holiday', 'shift', 'leave encashment',
  'cca', 'lta', 'da ', 'dearness', 'gross',
]

/** Lines that are TOTALS, not components — used to check, never added. */
const TOTAL_WORDS = [
  'total', 'gross', 'net pay', 'net salary', 'net amount', 'take home', 'netpay',
  'amount payable', 'net payable',
]

const has = (haystack: string, words: string[]) =>
  words.some((word) => haystack.includes(word))

/**
 * The document's own title, which is never a salary component.
 *
 * Also what `warnings` uses to decide whether this is a payslip at all, so the
 * one pattern serves both and they cannot disagree.
 */
const DOCUMENT_TITLE =
  /pay\s*slip|payslip|salary\s*slip|earnings\s*statement|pay\s*stub|statement\s*of\s*earnings/i

/* ------------------------------------------------------------- Primitives */

/**
 * A number as a payslip writes it: `1,23,456.78`, `1.234,56`, `(500.00)`,
 * `-500`, `₹ 5,000`.
 *
 * THE SEPARATORS ARE THE HARD PART, and getting them wrong moves a decimal
 * point, so the rule is explicit rather than a strip-everything-and-hope:
 *
 *   • Both `.` and `,` present → whichever comes LAST is the decimal point and
 *     the other is grouping. That reads `1,234.56` and `1.234,56` correctly
 *     without needing to know the locale.
 *   • Only `,` → ambiguous. A single comma with one or two digits after it is a
 *     decimal comma (`1234,5`); anything else is grouping (`1,234`, `1,23,456`
 *     — Indian lakh grouping, which is why the group sizes are not validated).
 *   • Only `.` → a single dot is a decimal point; several are grouping.
 *
 * Parentheses mean negative, as they do on every accounting document.
 */
function parseAmount(raw: string): number | null {
  const text = raw.trim()
  if (!text) return null
  const negative = /^\(.*\)$/.test(text) || text.startsWith('-')

  // Everything that is not a digit or a separator goes, including the currency
  // symbol and the sign — the sign is already captured above.
  const body = text.replace(/[^\d.,]/g, '')
  if (!/\d/.test(body)) return null

  const lastDot = body.lastIndexOf('.')
  const lastComma = body.lastIndexOf(',')
  let normalised: string

  if (lastDot >= 0 && lastComma >= 0) {
    const decimalAt = Math.max(lastDot, lastComma)
    const grouping = decimalAt === lastDot ? ',' : '.'
    normalised = `${body.slice(0, decimalAt).split(grouping).join('')}.${body.slice(decimalAt + 1)}`
  } else if (lastComma >= 0) {
    const commas = (body.match(/,/g) ?? []).length
    const decimals = body.length - lastComma - 1
    normalised =
      commas === 1 && decimals >= 1 && decimals <= 2
        ? body.replace(',', '.')
        : body.split(',').join('')
  } else if (lastDot >= 0) {
    const dots = (body.match(/\./g) ?? []).length
    normalised = dots === 1 ? body : body.split('.').join('')
  } else {
    normalised = body
  }

  const value = Number(normalised)
  if (!Number.isFinite(value)) return null
  return negative ? -value : value
}

/**
 * A whitespace-separated numeric token at the END of a line, with whatever came
 * before it.
 *
 * The anchor is `\s` rather than "anything", so `401k` and `01/05/2024` are not
 * mistaken for an amount column — a figure in a table is always separated from
 * its label by space.
 */
const TRAILING_COLUMN = /^(.*?)[\s:\u2026]+(\(?-?[$₹€£]?\s*[\d,.][\d,.]*\)?)$/

/**
 * Split a table row into its label and its numeric COLUMNS, left to right.
 *
 * This is what makes a multi-column layout readable. A US stub prints
 * `Regular  3,200.00  28,800.00` — this period, then year to date — and taking
 * only the last number off that line (which is what the first version of this
 * parser did) reads the year-to-date figure as the period's pay and leaves
 * `Regular 3,200.00` as the label. Peeling every trailing column instead gives
 * a clean label, the period amount from the FIRST column, and the YTD from the
 * last, which is what both layouts mean by that shape.
 *
 * Capped at four columns — rate, hours, this period, year to date is the widest
 * table either layout prints — so a row of a dozen figures is left alone rather
 * than being reduced to a one-word label.
 */
function splitRow(line: string): { label: string; columns: number[] } | null {
  let rest = line
  const columns: number[] = []
  for (let i = 0; i < 4; i += 1) {
    const match = TRAILING_COLUMN.exec(rest)
    if (!match) break
    const amount = parseAmount(match[2])
    if (amount === null) break
    columns.unshift(amount)
    rest = match[1].trim()
  }
  if (!columns.length) return null
  return { label: rest.replace(/[.:\u2026]+$/, '').trim(), columns }
}

/** `Label: value` on one line. */
function fieldAfter(lines: string[], patterns: RegExp[]): string {
  for (const line of lines) {
    for (const pattern of patterns) {
      const match = pattern.exec(line)
      if (match?.[1]) {
        const value = match[1].trim().replace(/^[:\-–—\s]+/, '').trim()
        // A label with nothing after it means the value is on the NEXT line in
        // a two-column layout; that is not something this can read, and an
        // empty string is the honest answer.
        if (value) return value.slice(0, 160)
      }
    }
  }
  return ''
}

/** `04-May-2020`, `04/05/2020`, `2020-05-04` → ISO. Empty when unreadable. */
function toIsoDate(raw: string): string {
  const text = raw.trim()
  let match = /^(\d{4})-(\d{1,2})-(\d{1,2})/.exec(text)
  if (match) {
    return `${match[1]}-${match[2].padStart(2, '0')}-${match[3].padStart(2, '0')}`
  }
  // `04-May-2020` / `4 May 2020`
  match = /^(\d{1,2})[\s\-/]+([A-Za-z]{3,})[\s\-/]+(\d{4})/.exec(text)
  if (match) {
    const month = MONTHS.findIndex((m) => m.startsWith(match![2].toLowerCase().slice(0, 3)))
    if (month >= 0) {
      return `${match[3]}-${String(month + 1).padStart(2, '0')}-${match[1].padStart(2, '0')}`
    }
  }
  // `05/04/2020` — AMBIGUOUS, and deliberately read as US month-first, because
  // that is the only layout in this product that carries explicit period dates.
  match = /^(\d{1,2})[/-](\d{1,2})[/-](\d{4})/.exec(text)
  if (match) {
    const a = Number(match[1])
    const b = Number(match[2])
    // A value over 12 can only be the day, which resolves the ambiguity for
    // most real dates; the rest fall back to month-first.
    const [month, day] = a > 12 ? [b, a] : [a, b]
    if (month >= 1 && month <= 12 && day >= 1 && day <= 31) {
      return `${match[3]}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`
    }
  }
  return ''
}

/** The currency the slip is written in, from its symbol or its code. */
function detectCurrency(text: string): string {
  if (/₹|\bINR\b|\bRs\.?\b/i.test(text)) return 'INR'
  if (/\bUSD\b|\bUS\$/.test(text)) return 'USD'
  if (/\bGBP\b|£/.test(text)) return 'GBP'
  if (/\bEUR\b|€/.test(text)) return 'EUR'
  if (/\bAED\b|د\.إ/.test(text)) return 'AED'
  if (/\bCAD\b|\bC\$/.test(text)) return 'CAD'
  if (/\bAUD\b|\bA\$/.test(text)) return 'AUD'
  if (/\bSGD\b|\bS\$/.test(text)) return 'SGD'
  // A bare `$` last, so `C$`/`A$`/`S$` above win over it.
  if (/\$/.test(text)) return 'USD'
  return ''
}

/** The month and year the slip is FOR, from a "Salary for May 2020" style line. */
function detectPeriod(text: string): { month: number | null; year: number | null } {
  const monthNames = MONTHS.join('|')
  const named = new RegExp(`\\b(${monthNames}|${MONTHS.map((m) => m.slice(0, 3)).join('|')})[a-z]*[\\s,\\-/']+(\\d{4})\\b`, 'i')
  const match = named.exec(text)
  if (match) {
    const key = match[1].toLowerCase().slice(0, 3)
    const month = MONTHS.findIndex((m) => m.startsWith(key))
    if (month >= 0) return { month: month + 1, year: Number(match[2]) }
  }
  // `05/2020` or `2020-05`, as a fallback.
  const numeric = /\b(0?[1-9]|1[0-2])[/-](20\d{2})\b/.exec(text) ?? null
  if (numeric) return { month: Number(numeric[1]), year: Number(numeric[2]) }
  const reversed = /\b(20\d{2})-(0?[1-9]|1[0-2])\b/.exec(text) ?? null
  if (reversed) return { month: Number(reversed[2]), year: Number(reversed[1]) }
  return { month: null, year: null }
}

