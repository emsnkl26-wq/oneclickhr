import 'server-only'

/**
 * Read a payslip PDF and work out what is on it (059).
 *
 * WHY THIS EXISTS. These payslips are not authored here — they come out of
 * whatever billing or payroll package the organization already runs, and the
 * admin receives a finished PDF. Re-typing twenty figures off that PDF into the
 * issue dialog is slow and it is the kind of slow that produces wrong numbers,
 * because nobody proofreads their own typing of a deductions table. So the PDF
 * is parsed and the dialog is PREFILLED; the admin then checks it and presses
 * the same Preview and Issue buttons as before.
 *
 * ┌──────────────────────────────────────────────────────────────────────────┐
 * │ A SUGGESTION, NEVER A SOURCE OF TRUTH.                                   │
 * │                                                                          │
 * │ Nothing in here is stored, nothing is issued, and nothing is believed    │
 * │ without a person looking at it. Every field comes back with the value    │
 * │ AND a note about how confident the parse was, the dialog says plainly    │
 * │ that it was read off a PDF, and an admin who presses Issue is the one    │
 * │ asserting the figures are right. Every field stays editable.             │
 * │                                                                          │
 * │ That framing is load-bearing. A parser that is quietly trusted turns one │
 * │ misread decimal point into somebody's wrong payslip, and the admin who   │
 * │ could have caught it was never shown the number.                         │
 * └──────────────────────────────────────────────────────────────────────────┘
 *
 * TEXT EXTRACTION, NOT IMAGE OCR. A payslip generated by software carries a
 * text layer, and reading it is exact — no character confusion, no 8-for-B. A
 * SCANNED payslip is pixels and yields nothing, which is detected and reported
 * as "this looks like a scan" rather than as an empty slip, because those are
 * different problems with different answers (re-export it as a PDF, versus
 * type it in). Running a real OCR model over the image case would mean shipping
 * or calling one, and would produce exactly the figures that must not be
 * trusted silently.
 *
 * HOW THE PARSE WORKS. Payslip layouts differ in everything except one habit:
 * a label on the left and its amount on the right of the same visual line. So
 * the text is split into lines, every line that ends in a number is treated as
 * `label → amount`, and the labels are then classified as earnings or
 * deductions by keyword. Totals are recognised and used as a CHECK rather than
 * as a line, which is what catches a column that was misread.
 */

// The response shape lives in a directive-free module so the payroll dialog can
// describe it without importing this server-only file. See its header.
